/** Unicode 13+ emojis that render as ▯ on Windows 10 without a color-emoji font */
const SAFE_EMOJI = {
  "🪙": "💰",
  "🪥": "🦷",
  "🪒": "✂️",
  "🪛": "🔧",
  "🪚": "🔨",
};

function safeEmoji(emoji) {
  return SAFE_EMOJI[emoji] ?? emoji;
}

function normalizeGrams(grams) {
  if (grams < 1) {
    return Math.round(grams * 1000) / 1000;
  }
  if (grams < 100) {
    return Math.round(grams * 10) / 10;
  }
  return Math.round(grams);
}

function validateItem(item) {
  const dumbbell = item.one.match(/^гантель (\d+(?:\.\d+)?) кг$/);
  if (dumbbell) {
    const expected = parseFloat(dumbbell[1]) * 1000;
    if (Math.abs(item.grams - expected) > expected * 0.02) {
      throw new Error(
        `${item.one}: вес ${item.grams} г, ожидается ~${expected} г`
      );
    }
  }

  for (const field of [item.one, item.few, item.many]) {
    if (/серия|№/i.test(field)) {
      throw new Error(`${item.one}: не допускаются «серия» и «№» в названии`);
    }
  }

  if (item.grams <= 0) {
    throw new Error(`${item.one}: вес должен быть > 0`);
  }
}

function add(map, item) {
  const grams = normalizeGrams(item.grams);
  if (grams <= 0) return;
  const normalized = { ...item, emoji: safeEmoji(item.emoji), grams };
  validateItem(normalized);
  const key = `${normalized.one}\0${normalized.grams}`;
  if (!map.has(key)) map.set(key, normalized);
}

